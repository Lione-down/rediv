def _box(name: bytes, payload: bytes) -> bytes:
    return struct.pack(">I4s", len(payload) + 8, name) + payload


def _bmff_file(brand: bytes) -> bytes:
    compatible = b"qt  " if brand == b"qt  " else (b"M4A " if brand == b"M4A " else b"isom")
    ftyp_payload = brand + b"\x00\x00\x00\x00" + compatible
    handler_type = b"soun" if brand == b"M4A " else b"vide"
    handler = _box(b"hdlr", b"\x00" * 8 + handler_type + b"\x00" * 12)
    moov = _box(b"moov", _box(b"trak", _box(b"mdia", handler)))
    return _box(b"ftyp", ftyp_payload) + moov + _box(b"mdat", b"\x00\x00\x00\x01")


def _ebml_element(element_id: bytes, payload: bytes) -> bytes:
    return element_id + bytes([0x80 | len(payload)]) + payload


def _webm_file() -> bytes:
    ebml = _ebml_element(b"\x1a\x45\xdf\xa3", _ebml_element(b"\x42\x82", b"webm"))
    tracks = _ebml_element(
        b"\x16\x54\xae\x6b",
        _ebml_element(b"\xae", _ebml_element(b"\x83", b"\x01")),
    )
    simple_block = _ebml_element(b"\xa3", b"\x81\x00\x00\x00\x00")
    cluster = _ebml_element(b"\x1f\x43\xb6\x75", simple_block)
    return ebml + _ebml_element(b"\x18\x53\x80\x67", tracks + cluster)


def _webp_file() -> bytes:
    bitstream = b"\x2f\x00\x00\x00\x00\x00"
    payload = b"WEBPVP8L" + struct.pack("<I", len(bitstream)) + bitstream
    return b"RIFF" + struct.pack("<I", len(payload)) + payload


def _flac_file() -> bytes:
    sample_data = (8000 << 44) | (15 << 36) | 1
    stream_info = b"\x00\x10\x00\x10" + (b"\x00" * 6) + sample_data.to_bytes(8, "big") + (b"\x00" * 16)
    return b"fLaC\x80\x00\x00\x22" + stream_info + b"\xff\xf8\x00\x00\x00\x00"


def _ogg_crc(content: bytes) -> int:
    checksum = 0
    for byte in content:
        checksum ^= byte << 24
        for _ in range(8):
            checksum = (
                ((checksum << 1) ^ 0x04C11DB7) & 0xFFFFFFFF
                if checksum & 0x80000000
                else (checksum << 1) & 0xFFFFFFFF
            )
    return checksum


def _ogg_page(header_type: int, sequence: int, payload: bytes) -> bytes:
    header = bytearray(
        b"OggS\x00"
        + bytes([header_type])
        + (b"\x00" * 8)
        + (1).to_bytes(4, "little")
        + sequence.to_bytes(4, "little")
        + (b"\x00" * 4)
        + b"\x01"
        + bytes([len(payload)])
    )
    header[22:26] = _ogg_crc(bytes(header) + payload).to_bytes(4, "little")
    return bytes(header) + payload


def _ogg_file() -> bytes:
    opus_head = b"OpusHead\x01\x01\x00\x00\x80\xbb\x00\x00\x00\x00\x00"
    return _ogg_page(0x02, 0, opus_head) + _ogg_page(0x04, 1, b"\x00")


def _wav_file() -> bytes:
    fmt = b"\x01\x00\x01\x00\x40\x1f\x00\x00\x80>\x00\x00\x02\x00\x10\x00"
    payload = b"WAVE" + b"fmt " + struct.pack("<I", len(fmt)) + fmt + b"data\x02\x00\x00\x00\x00\x00"
    return b"RIFF" + struct.pack("<I", len(payload)) + payload


